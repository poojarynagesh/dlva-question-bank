"""Build assets/search-index.js.

Run after adding or editing a page or a question bank:  python tools/build_index.py

Indexes the h2/h3 headings of the static pages, every lecture's title, its
"what to revise" points and every question stem in its bank (assets/qb/Lxx.js),
each linked to the lecture page.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from make_pages import LECTURES  # noqa: E402

STATIC = [
    ("home", "index.html"),
    ("format", "exam-format.html"),
    ("sample", "sample-midterm.html"),
    ("mock", "mock-paper.html"),
]
HEAD = re.compile(r'<h([23])([^>]*)>(.*?)</h\1>', re.S)
RAW = re.compile(r"R`(.*?)`", re.S)


def text(fragment):
    s = re.sub(r"<[^>]+>", " ", fragment)
    s = re.sub(r"\$\$.*?\$\$", " ", s, flags=re.S)
    s = re.sub(r"\$([^$]*)\$", lambda m: re.sub(r"\\[a-zA-Z]+|[{}^_]", " ", m.group(1)), s)
    return re.sub(r"\s+", " ", html.unescape(s)).strip()


def clip(s, n=110):
    return s if len(s) <= n else s[:n].rsplit(" ", 1)[0] + " …"


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:60]


def main():
    available, entries = [], []
    for pid, rel in STATIC:
        path = ROOT / rel
        if not path.exists():
            continue
        available.append(pid)
        src = path.read_text(encoding="utf-8")
        m = re.search(r"<title>(.*?)</title>", src, re.S)
        where = text(m.group(1)).split(" — ")[0] if m else rel
        for h in HEAD.finditer(src):
            label = text(h.group(3))
            idm = re.search(r'id="([^"]+)"', h.group(2))
            entries.append({"t": label, "p": where, "u": f"{rel}#{idm.group(1) if idm else slug(label)}"})
    for lid, date, nav, title, lead, phase in LECTURES:
        bank = ROOT / "assets" / "qb" / f"{lid}.js"
        if not bank.exists():
            continue
        available.append(lid)
        rel = f"lectures/{lid}.html"
        where = f"Lecture {int(lid[1:])}"
        entries.append({"t": title, "p": f"{where} · {date}", "u": rel})
        src = bank.read_text(encoding="utf-8")
        pts = re.search(r"points:\s*\[(.*?)\n\s*\],", src, re.S)
        for p in RAW.findall(pts.group(1) if pts else ""):
            entries.append({"t": clip(text(p)), "p": f"{where} · Revise", "u": rel + "#qb-points", "k": "Revise"})
        for sec, kind in (("mcq", "MCQ"), ("short", "Short"), ("long", "Long")):
            block = re.search(r"\n    " + sec + r":\s*\[(.*?)\n    \],", src, re.S)
            if not block:
                continue
            anchor = "sec-" + sec
            for q in re.findall(r"\bq:\s*R`(.*?)`", block.group(1), re.S):
                entries.append({"t": clip(text(q)), "p": f"{where} · {kind}", "u": f"{rel}#{anchor}", "k": kind})
    out = ROOT / "assets" / "search-index.js"
    out.write_text(
        "// Generated by tools/build_index.py — do not edit by hand.\n"
        f"window.RL_AVAILABLE = {json.dumps(available)};\n"
        f"window.RL_SEARCH = {json.dumps(entries, ensure_ascii=False, indent=0)};\n",
        encoding="utf-8",
    )
    print(f"indexed {len(entries)} entries from {len(available)} pages")


if __name__ == "__main__":
    main()
